// Turns an EMS single-line SVG font into `src/ink/stroke-font-data.ts`. Run: node scripts/build-stroke-font.mjs <EMSTech.svg>
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const CURVE_STEPS = 6;
const COMMAND = /([MLC])([^MLC]*)/g;
const ENTITY = { '&quot;': '"', '&amp;': '&', '&lt;': '<', '&gt;': '>', '&apos;': "'" };

function decode(unicode) {
  return unicode.replace(/&#x([0-9a-f]+);/gi, (_, code) => String.fromCodePoint(parseInt(code, 16))).replace(/&\w+;/g, (entity) => ENTITY[entity] ?? entity);
}

function flattenCurve(from, [x1, y1, x2, y2, x3, y3]) {
  return Array.from({ length: CURVE_STEPS }, (_, step) => {
    const t = (step + 1) / CURVE_STEPS;
    const u = 1 - t;
    return [u * u * u * from[0] + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t * t * t * x3, u * u * u * from[1] + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t * t * t * y3];
  });
}

function readStrokes(path) {
  const strokes = [];
  for (const [, command, numbers] of path.matchAll(COMMAND)) {
    const values = numbers.trim().split(/[\s,]+/).filter(Boolean).map(Number);
    if (command === 'M') strokes.push([values.slice(0, 2)]);
    if (command === 'L') for (let index = 0; index < values.length; index += 2) strokes.at(-1).push(values.slice(index, index + 2));
    if (command === 'C') for (let index = 0; index < values.length; index += 6) strokes.at(-1).push(...flattenCurve(strokes.at(-1).at(-1), values.slice(index, index + 6)));
  }
  return strokes.map((stroke) => stroke.flat().map(Math.round));
}

const svg = readFileSync(process.argv[2], 'utf8');
const defaultAdvance = Number(/<font [^>]*horiz-adv-x="([\d.]+)"/.exec(svg)[1]);
const glyphs = [...svg.matchAll(/<glyph\b([^>]*)\/>/g)].map(([, attributes]) => {
  const character = decode(/unicode="([^"]*)"/.exec(attributes)[1]);
  const advance = Number(/horiz-adv-x="([\d.]+)"/.exec(attributes)?.[1] ?? defaultAdvance);
  return [character, Math.round(advance), readStrokes(/\bd="([^"]*)"/.exec(attributes)?.[1] ?? '')];
}).filter(([character]) => [...character].length === 1);

const output = `// Generated by scripts/build-stroke-font.mjs from EMS Tech, by Sheldon B. Michaels and Windell H. Oskay, a derivative of Architects Daughter by Kimberly Geswein.
// SIL Open Font License 1.1. See docs/credits.md. Do not edit by hand.
export const STROKE_FONT_METRICS = { unitsPerEm: 1000, ascent: 800, descent: 200, spaceAdvance: ${defaultAdvance} } as const;

/** Each glyph is its character, its advance, and its strokes as flat x, y lists, with y up. */
export const STROKE_FONT_GLYPHS: readonly (readonly [string, number, readonly (readonly number[])[]])[] = ${JSON.stringify(glyphs)};
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '../src/ink/stroke-font-data.ts'), output);
console.log(`${glyphs.length} glyphs, ${output.length} bytes`);
