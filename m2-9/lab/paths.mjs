// Two students on one browser: a tab follows a user switch through restartAppAtHome, and no tab may loop. Run with `built` or `signedout`, which swaps the message for a real SIGNED_OUT shape.
import { launch, newLane, track, WEB, OTHER, sleep, logger, ensureUser, passwordSession, emailLink, MAYA } from './lib.mjs';
const [, , shape = 'built', headed = 'headless'] = process.argv;
const log = logger(`paths-${shape}-${headed}`);
await ensureUser(MAYA);
const browser = await launch(headed === 'headed' ? { headless: false } : {});
const lane = `paths-${shape}-${Date.now()}`;
const context = await newLane(browser, lane);
if (shape === 'signedout') await context.addInitScript(() => { const post = BroadcastChannel.prototype.postMessage; BroadcastChannel.prototype.postMessage = function (message) { post.call(this, message?.event === 'ASTRA_DROP_KEPT_PAGE' ? { event: 'SIGNED_OUT', session: null } : message); }; });
const nia = { email: `m29-nia-${Date.now()}@astra.test` };
const asked = Date.now();
const P = await context.newPage();
await P.goto(`${WEB}/`);
await P.getByRole('button', { name: 'Continue with email' }).click();
await P.getByRole('textbox', { name: 'Your email address' }).fill(nia.email);
await P.getByRole('button', { name: 'Send link' }).click();
await P.getByRole('heading', { name: 'Check your email.' }).waitFor();
await P.close();
const link = await emailLink(nia.email, asked);
const session = await passwordSession(MAYA);
const seed = await context.newPage();
await seed.goto(`${OTHER}/`);
await seed.goto(`${WEB}/terms`);
await seed.evaluate((value) => localStorage.setItem('astra-session', value), JSON.stringify(session));
await seed.close();
const kept = await context.newPage();
await kept.goto(`${OTHER}/`);
await kept.goto(`${WEB}/`);
await kept.getByRole('heading', { name: /Welcome back/ }).waitFor({ timeout: 15000 });
await kept.goto(`${OTHER}/`);
const B = await context.newPage();
const bEvents = []; track(B, bEvents);
await B.goto(`${WEB}/`);
await B.getByRole('heading', { name: /Welcome back/ }).waitFor({ timeout: 15000 });
const navigations = { B: 0, C: 0 };
B.on('framenavigated', (frame) => { if (frame === B.mainFrame()) navigations.B += 1; });
const C = await context.newPage();
C.on('framenavigated', (frame) => { if (frame === C.mainFrame()) navigations.C += 1; });
await C.goto(link);
await sleep(6000);
const read = (page) => page.evaluate(() => ({ path: location.pathname, h1: document.querySelector('h1')?.innerText ?? null, vis: document.documentElement.style.visibility || 'shown', who: JSON.parse(localStorage.getItem('astra-session') ?? 'null')?.user?.email ?? null })).catch((error) => ({ error: String(error).slice(0, 80) }));
log({ shape, navigationsIn6s: navigations, B: await read(B), C: await read(C) });
const before = { ...navigations };
await sleep(4000);
log({ furtherNavigationsIn4s: { B: navigations.B - before.B, C: navigations.C - before.C } });
await browser.close();
log('PATHS DONE');
