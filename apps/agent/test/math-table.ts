const range = (from: number, to: number) => Array.from({ length: to - from + 1 }, (_, index) => from + index);

function getLinearSolutionSteps(): Step[] {
  return range(2, 9).flatMap((coefficient) =>
    [1, 3, 7, 30, 100].flatMap((constant) =>
      [2, 5, 10, 100].flatMap((answer) => {
        const total = coefficient * answer + constant;
        return [
          [`${coefficient}x + ${constant} = ${total}`, `${coefficient}x = ${total} - ${constant}`],
          [`${coefficient}x = ${total} - ${constant}`, `${coefficient}x = ${total - constant}`],
          [`${coefficient}x = ${total - constant}`, `x = ${answer}`],
        ] as Step[];
      }),
    ),
  );
}

